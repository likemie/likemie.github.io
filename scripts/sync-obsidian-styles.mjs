import { readFile, writeFile } from "node:fs/promises"
import { resolve } from "node:path"
import { createHash } from "node:crypto"
import { pathToFileURL } from "node:url"

// Never edit the vault. Keep semantic Obsidian variables intact: the web
// bridge supplies their values, instead of mapping muted text to Quartz gray.
export function adaptObsidianCss(source) {
  return (
    source
      // Obsidian puts theme classes on body; Quartz puts saved-theme on html.
      // Match both the root and body so compound selectors such as
      // body.theme-dark and :where(.theme-dark *) retain their meaning/specificity.
      .replace(/\.theme-dark\b/g, ':is([saved-theme="dark"], body:where([saved-theme="dark"] *))')
      .replace(
        /\.theme-light\b/g,
        ':is(:root:where(:not([saved-theme="dark"])), body:where(:root:not([saved-theme="dark"]) *))',
      )
      .replace(/\.internal-link(?![\w-])/g, ".internal")
      .replace(/\.external-link(?![\w-])/g, ".external")
      .replace(/\.markdown-preview-view\b|\.markdown-rendered\b/g, "article")
      // MathJax display containers become KaTeX display/standalone formula nodes.
      .replace(
        /mjx-container\[display="true"\]/g,
        ":is(.katex-display, p:has(> .katex:only-child), p:has(> .katex + br + .katex))",
      )
      .replace(/mjx-container/g, ".katex")
      // Obsidian resolves named icons in JS; Quartz uses CSS SVG masks.
      // Keep the existing Quartz SVG overrides, not invalid named mask values.
      .replace(/--callout-icon:\s*lucide-[\w-]+\s*;/g, "")
      // The source passes a hex variable to rgba(), which requires RGB channels.
      .replace(/rgba\(var\(--color-base-100\),/g, "rgba(var(--mono-rgb-100),")
      .replace(/[ \t]+$/gm, "")
  )
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const vault = resolve(process.argv[2] ?? "content")
  const source = await readFile(resolve(vault, ".obsidian/snippets/argument-callouts.css"), "utf8")
  const normalizedCss = adaptObsidianCss(source)
  const hash = createHash("sha256").update(source).digest("hex")
  await writeFile(
    new URL("../quartz/styles/argument-callouts.scss", import.meta.url),
    `/* Generated by scripts/sync-obsidian-styles.mjs. Do not edit.\n   Source SHA-256: ${hash}\n   Web overrides belong in quartz-callout-overrides.scss. */\n\n${normalizedCss}`,
  )
  console.log(`Synced Obsidian callouts (${source.split("\n").length} lines, ${hash.slice(0, 12)})`)
}
